#!/usr/bin/env node
// Regenerates src/catalog.ts from a CoolerControl OpenAPI document.
//
//   node scripts/generate-catalog.mjs path/to/openapi.json [version]
//
// The document lives in the CoolerControl repo at openapi/openapi.json (release
// daemons don't serve it). Only operations a bearer token may call are kept;
// cookie-only routes (login, tokens, shutdown, plugins, stress tests) and the
// SSE streams are left out because this server cannot use them.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const [specPath, version = "unknown"] = process.argv.slice(2);
if (!specPath) {
  console.error("usage: generate-catalog.mjs <openapi.json> [coolercontrol-version]");
  process.exit(2);
}

const spec = JSON.parse(readFileSync(specPath, "utf8"));
const METHODS = ["get", "post", "put", "patch", "delete"];
const entries = [];

for (const [path, item] of Object.entries(spec.paths)) {
  if (path.startsWith("/sse")) continue;
  for (const method of METHODS) {
    const op = item[method];
    if (!op) continue;
    const security = op.security ?? spec.security ?? [];
    if (!security.some((s) => "BearerAuth" in s)) continue;

    const content = Object.keys(op.requestBody?.content ?? {});
    const body = content.find((c) => c.startsWith("multipart/"))
      ? "multipart"
      : content.find((c) => c.startsWith("text/"))
        ? "text"
        : content.length
          ? "json"
          : undefined;
    const query = (op.parameters ?? []).filter((p) => p.in === "query").map((p) => p.name);
    const schemaRef = op.requestBody?.content?.["application/json"]?.schema?.$ref;

    entries.push({
      method: method.toUpperCase(),
      path,
      summary: op.summary ?? "",
      tag: op.tags?.[0] ?? "",
      ...(body ? { body } : {}),
      ...(schemaRef ? { bodySchema: schemaRef.split("/").pop() } : {}),
      ...(query.length ? { query } : {}),
    });
  }
}

const out = `// Generated by scripts/generate-catalog.mjs from the CoolerControl ${version} OpenAPI
// document. Do not edit by hand.

export interface Endpoint {
  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  path: string;
  summary: string;
  tag: string;
  body?: "json" | "multipart" | "text";
  bodySchema?: string;
  query?: string[];
}

export const COOLERCONTROL_API_VERSION = ${JSON.stringify(version)};

export const ENDPOINTS: Endpoint[] = ${JSON.stringify(entries, null, 2)};
`;

const target = fileURLToPath(new URL("../src/catalog.ts", import.meta.url));
writeFileSync(target, out);
console.error(`wrote ${entries.length} endpoints to ${target}`);
